import { test, expect } from "@playwright/test";

for (const width of [1280, 390]) {
  test(`calendar and preparation form one advisor workflow at ${width}px`, async ({ page, request }, testInfo) => {
    await page.setViewportSize({ width, height: 900 });
    await expect.poll(async () => (await (await request.get("/api/calendar")).json()).processing).toBe(false);
    expect((await request.post("/api/calendar/simulation", { data: { action: "reset" } })).ok()).toBe(true);
    await expect.poll(async () => (await (await request.get("/api/calendar")).json()).preparations.filter(job => job.status === "ready").length).toBe(2);
    let manualGenerations = 0;
    page.on("request", req => { if (req.method() === "POST" && req.url().endsWith("/api/briefings")) manualGenerations += 1; });
    await page.goto("/");
    const calendar = page.getByRole("region", { name: "Weekly calendar" });
    await expect(calendar).toBeVisible();
    await expect(page.locator(".calendar-day-heading")).toHaveCount(5);
    await expect(page.locator(".calendar-meeting")).toHaveCount(29);
    const notice = page.getByRole("dialog");
    await expect(notice).toContainText("Your brief for Garcia Family is ready");
    await page.screenshot({ path: testInfo.outputPath("calendar-notice.png"), fullPage: true });
    await notice.getByRole("button", { name: "View meeting prep", exact: true }).click();
    await expect(page.getByRole("article", { name: "Meeting briefing" })).toContainText("Garcia Family");
    await expect(page.getByRole("region", { name: "Meeting at a glance" })).toBeVisible();
    await expect(page.getByLabel("Generation mode")).toHaveCount(0);
    await page.getByRole("button", { name: "Back to calendar", exact: true }).click();
    await expect(calendar).toBeVisible();
    // Only one automatic popup per page visit; remaining briefs are discoverable in the list.
    await expect(notice).toHaveCount(0);
    await page.waitForTimeout(150);
    await page.screenshot({ path: testInfo.outputPath("calendar-week.png"), fullPage: true });
    await page.getByRole("button", { name: /^Event details: Operations check-in/ }).click();
    await expect(notice).toContainText("No client brief needed for this event.");
    await expect(notice.getByRole("button", { name: "View meeting prep" })).toHaveCount(0);
    await expect(notice.locator("dl")).toContainText("TypeInternal meeting");
    await page.screenshot({ path: testInfo.outputPath("event-details.png"), fullPage: true });
    await notice.getByRole("button", { name: "Close event details" }).click();
    if (width < 768) await page.locator(".calendar-day-heading").nth(2).click();
    await page.getByRole("button", { name: /^View meeting prep for Okafor Family on 2026-11-11/ }).click();
    await expect(page.getByRole("article", { name: "Meeting briefing" })).toContainText("Okafor Family");
    await expect(page.locator(".meeting-section")).toHaveCount(6);
    await expect(page.locator(".calendar-prep-context h2")).toHaveText("Okafor Family");
    await page.getByRole("button", { name: "Mark as reviewed", exact: true }).click();
    await expect(page.locator(".calendar-prep-context .chip")).toHaveText("Reviewed");
    if (width >= 768) await expect(page.getByRole("button", { name: "Open preparation for Okafor Family on 2026-11-11", exact: true })).toContainText("Reviewed");
    await expect(page.locator(".prep-hub-heading")).toContainText("1 brief is ready");
    await page.screenshot({ path: testInfo.outputPath("meeting-brief.png"), fullPage: true });
    await page.getByRole("button", { name: "Back to calendar", exact: true }).click();
    if (width < 768) await page.getByLabel("Navigate to page").selectOption("meeting");
    else await page.getByRole("button", { name: "Meeting Prep", exact: true }).click();
    await expect(page.getByRole("region", { name: "Meeting preparation workspace" })).toBeVisible();
    await expect(page.getByRole("button", { name: "Open preparation for Okafor Family on 2026-11-11", exact: true })).toContainText("Reviewed");
    await page.screenshot({ path: testInfo.outputPath("meeting-workspace.png"), fullPage: true });
    await page.getByRole("button", { name: "Open preparation for Okafor Family on 2026-11-11", exact: true }).click();
    await expect(page.locator(".calendar-prep-context .chip")).toHaveText("Reviewed");
    await page.getByRole("button", { name: "Edit draft", exact: true }).click();
    await page.getByLabel("Client Overview: item details").first().fill("Advisor updated draft for the meeting.");
    await expect(page.locator(".calendar-prep-context .chip")).toHaveText("Draft for your review");
    await page.getByRole("button", { name: "Done editing", exact: true }).click();
    if (width < 768) await page.getByRole("button", { name: "All meetings", exact: true }).click();
    await page.getByLabel("Search client meetings").fill("Chen");
    await expect(page.locator(".prep-meeting-row")).toHaveCount(2);
    await page.getByRole("button", { name: "Open preparation for Chen Household on 2026-11-13", exact: true }).click();
    await expect(page.getByRole("region", { name: "Scheduled preparation" })).toContainText("24 hours before");
    const before = await (await request.get("/api/calendar")).json();
    expect(before.preparations).toHaveLength(2);
    await page.getByRole("button", { name: "Prepare early", exact: true }).click();
    await expect(page.getByRole("article", { name: "Meeting briefing" })).toContainText("Chen Household");
    await page.getByRole("button", { name: "Back to calendar", exact: true }).click();
    await page.getByRole("button", { name: "Next week", exact: true }).click();
    await expect(page.locator(".calendar-date-navigation h3")).toContainText("November 16");
    await expect(page.locator(".calendar-meeting.category-client")).toHaveCount(3);
    await page.getByRole("button", { name: "Today", exact: true }).click();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    expect(manualGenerations).toBe(0);
    const after = await (await request.get("/api/calendar")).json();
    expect(after.preparations).toHaveLength(3);
    expect(after.preparations.every(job => job.status === "ready")).toBe(true);
    await request.post("/api/calendar/simulation", { data: { action: "pause" } });
    if (width < 768) await page.getByLabel("Navigate to page").selectOption("meeting");
    else await page.getByRole("button", { name: "Meeting Prep", exact: true }).click();
    await expect(page.locator(".prep-hub-heading")).toContainText("Automatic preparation is paused. Existing briefs remain available.");
    await page.screenshot({ path: testInfo.outputPath("meeting-paused.png"), fullPage: true });
  });
}
